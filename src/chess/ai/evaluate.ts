const ENDGAME_NON_PAWN_THRESHOLD = 2600

/** Static evaluation in centipawns, positive means good for White. */
export function evaluate(game: Chess): number {
  const board = game.board()
  let nonPawnMaterial = 0
  for (const row of board) {
    for (const cell of row) {
      if (cell && cell.type !== 'p' && cell.type !== 'k') {
        nonPawnMaterial += MATERIAL[cell.type]
      }
    }
  }
  const endgame = nonPawnMaterial <= ENDGAME_NON_PAWN_THRESHOLD
  const kingTable = endgame ? KING_END_PST : KING_MID_PST

  let score = 0
  for (let row = 0; row < 8; row++) {
    for (let col = 0; col < 8; col++) {
      const cell = board[row][col]
      if (!cell) continue
      const table = cell.type === 'k' ? kingTable : PST[cell.type]
      const material = MATERIAL[cell.type]
      if (cell.color === 'w') {
        score += material + table[row * 8 + col]
      } else {
        score -= material + table[(7 - row) * 8 + col]
      }
    }
  }
  return score
}
